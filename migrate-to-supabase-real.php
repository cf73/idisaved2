<?php

require_once 'vendor/autoload.php';

use Aws\S3\S3Client;
use Aws\Exception\AwsException;

class RealS3ToSupabaseMigrator
{
    private $s3Client;
    private $bucket;
    private $supabaseUrl;
    private $supabaseKey;
    private $tempDir;
    private $batchSize = 50;
    private $processedCount = 0;
    private $errorCount = 0;
    private $startTime;
    private $progressFile = 'migration-progress.json';

    public function __construct()
    {
        $this->loadEnv();
        $this->tempDir = 'temp';
        $this->startTime = microtime(true);

        // Initialize S3 client with SSL verification disabled
        $this->s3Client = new S3Client([
            'version' => 'latest',
            'region' => $_ENV['AWS_DEFAULT_REGION'],
            'credentials' => [
                'key' => $_ENV['AWS_ACCESS_KEY_ID'],
                'secret' => $_ENV['AWS_SECRET_ACCESS_KEY'],
            ],
            'http' => [
                'verify' => false,
            ],
        ]);
        
        $this->bucket = $_ENV['AWS_BUCKET'];
        $this->supabaseUrl = $_ENV['SUPABASE_URL'] ?? '';
        $this->supabaseKey = $_ENV['SUPABASE_ANON_KEY'] ?? '';

        if (empty($this->supabaseUrl) || empty($this->supabaseKey)) {
            throw new Exception("Supabase URL or Anon Key is not configured in your .env file.");
        }
    }

    private function loadEnv()
    {
        $envFile = '.env';
        if (file_exists($envFile)) {
            $lines = file($envFile, FILE_IGNORE_NEW_LINES | FILE_SKIP_EMPTY_LINES);
            foreach ($lines as $line) {
                if (strpos($line, '=') !== false && strpos($line, '#') !== 0) {
                    list($key, $value) = explode('=', $line, 2);
                    $_ENV[trim($key)] = trim($value, '"');
                }
            }
        }
    }

    public function runFullMigration()
    {
        echo "=== REAL S3 TO SUPABASE MIGRATION ===\n";
        echo "This will insert data into your existing Supabase tables.\n";
        echo "Bucket: {$this->bucket}\n";
        echo "Start time: " . date('Y-m-d H:i:s') . "\n\n";

        // $this->createSupabaseTables(); // No longer needed, tables created manually.

        $totalObjects = $this->getTotalObjectCount();
        echo "Total objects to migrate: {$totalObjects}\n";
        echo "Batch size: {$this->batchSize}\n\n";

        $this->createProgressFile($totalObjects);

        $continuationToken = null;
        do {
            $result = $this->listS3ContentsBatch($continuationToken);
            $this->processBatch($result['objects']);
            $continuationToken = $result['continuationToken'];

            $this->saveProgress();
            $this->showProgress($totalObjects);
            usleep(100000); // 0.1 second delay

        } while ($continuationToken);

        $this->showFinalResults($totalObjects);
    }

